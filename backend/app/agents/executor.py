
from app.agents.coordinator import execute_step


def execute_plan(
    plan,
    message: str,
    history: str = ""
):
    """
    Execute every step generated by the planner.

    Each step is routed through the coordinator,
    which decides whether to use:

    - Document Agent
    - Web Agent
    - Chat Agent
    """

    outputs = []

    if not isinstance(plan, list):

        return [
            {
                "answer": "Invalid execution plan.",
                "sources": []
            }
        ]

    for step in plan:

        if not isinstance(step, dict):

            outputs.append(
                {
                    "answer": "Invalid plan step.",
                    "sources": []
                }
            )

            continue

        try:

            result = execute_step(
                step=step,
                message=message,
                history=history
            )

            if isinstance(result, dict):

                outputs.append(result)

            else:

                outputs.append(
                    {
                        "answer": str(result),
                        "sources": []
                    }
                )

        except Exception as e:

            print(
                f"Executor step error: {str(e)}"
            )

            outputs.append(
                {
                    "answer": f"Executor Error: {str(e)}",
                    "sources": []
                }
            )

    return outputs

